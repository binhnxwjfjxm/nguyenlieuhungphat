export function normalizeCatalogText(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("vi")
    .trim();
}

export function cloneProduct(product: Product): Product {
  return {
    ...product,
    aliases: [...product.aliases],
    price: { ...product.price },
  };
}
